export function isSupportedCurrency(code) { return typeof code === "string" && CODE_SET.has(code); }
const SPECIAL_FLAGS = { EUR: "🇪🇺", XAF: "🌍", XOF: "🌍", XCD: "🌎", XCG: "🌎", XPF: "🌏" };
export function currencyFlag(code) { if (SPECIAL_FLAGS[code]) return SPECIAL_FLAGS[code]; return [...code.slice(0, 2)].map((c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65)).join(""); }
